#!/usr/bin/env python3
"""Generate .NET record layouts and PostgreSQL DDL from the estate copybooks.

The copybook parser is the repository's own (tools/parity/copybook.py), so the
.NET codec, the relational schema and the parity comparator share one
definition of every field.

  src/CardDemo.Domain/Layouts.g.cs
  db/migrations/001_create_vsam_tables.sql
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "tools" / "parity"))
import copybook  # noqa: E402

BATCH = ROOT / "batch-dotnet"

# copybook -> (C# name, VSAM table or None, primary key fields)
LAYOUTS = {
    "CVACT01Y": ("Account", "acctdata", ["ACCT-ID"]),
    "CVACT02Y": ("Card", "carddata", ["CARD-NUM"]),
    "CVACT03Y": ("CardXref", "cardxref", ["XREF-CARD-NUM"]),
    "CVTRA01Y": ("TranCatBal", "tcatbalf", ["TRANCAT-ACCT-ID", "TRANCAT-TYPE-CD", "TRANCAT-CD"]),
    "CVTRA02Y": ("DisclosureGroup", "discgrp", ["DIS-ACCT-GROUP-ID", "DIS-TRAN-TYPE-CD", "DIS-TRAN-CAT-CD"]),
    "CVTRA03Y": ("TranType", "trantype", ["TRAN-TYPE"]),
    "CVTRA04Y": ("TranCategory", "trancatg", ["TRAN-TYPE-CD", "TRAN-CAT-CD"]),
    "CVTRA05Y": ("Transaction", "transact", ["TRAN-ID"]),
    "CVTRA06Y": ("DailyTransaction", None, []),
    "REJTRAN": ("RejectRecord", None, []),
}


def cs_name(name: str) -> str:
    return "".join(p.capitalize() for p in name.split("-"))


def sql_name(name: str) -> str:
    return name.lower().replace("-", "_")


def main() -> int:
    cs = ["// <auto-generated> by batch-dotnet/tools/codegen/gen_layouts.py from app/cpy - do not edit </auto-generated>",
          "namespace CardDemo.Domain;", "", "public static class Layouts", "{"]
    ddl = ["-- generated by batch-dotnet/tools/codegen/gen_layouts.py from app/cpy - do not edit",
           "-- One table per VSAM KSDS; columns follow the copybook, numeric fields keep their PIC precision.", ""]
    for cpy, (name, table, keys) in LAYOUTS.items():
        fields = copybook.parse_copybook(cpy)
        length = copybook.record_length(fields)
        cs.append(f"    [Trace(\"{cpy}\")]")
        cs.append(f"    public static readonly RecordLayout {name} = new(\"{cpy}\", {length}, new FieldSpec[]")
        cs.append("    {")
        for f in fields:
            cs.append(f"        new(\"{f.name}\", {f.offset}, {f.length}, FieldKind.{ {'text': 'Text', 'display': 'Zoned', 'comp-3': 'Packed', 'comp': 'Binary'}[f.kind] }, {f.scale}, {str(f.signed).lower()}, {f.digits}),")
        cs.append("    });")
        cs.append("")
        if table:
            cols = []
            for f in fields:
                if f.is_filler:
                    continue
                typ = f"varchar({f.length})" if f.kind == "text" else f"numeric({f.digits},{f.scale})"
                cols.append(f"    {sql_name(f.name)} {typ} NOT NULL")
            cols.append(f"    PRIMARY KEY ({', '.join(sql_name(k) for k in keys)})")
            ddl += [f"-- {cpy}: {length}-byte record", f"CREATE TABLE IF NOT EXISTS vsam_{table} (", ",\n".join(cols), ");", ""]
    cs.append("}")
    (BATCH / "src" / "CardDemo.Domain" / "Layouts.g.cs").write_text("\n".join(cs) + "\n")
    ddl += ["CREATE INDEX IF NOT EXISTS vsam_cardxref_acct_aix ON vsam_cardxref (xref_acct_id);  -- CARDXREF.VSAM.AIX", ""]
    (BATCH / "db" / "migrations" / "001_create_vsam_tables.sql").write_text("\n".join(ddl))
    print(f"generated {len(LAYOUTS)} layouts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
